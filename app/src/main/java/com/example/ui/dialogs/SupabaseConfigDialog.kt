@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SupabaseConfigDialog(
    viewModel: HealthViewModel,
    onDismiss: () -> Unit
) {
    val context = LocalContext.current
    val coroutineScope = rememberCoroutineScope()

    var urlInput by remember { mutableStateOf(SupabaseConfig.getSupabaseUrl(context)) }
    var keyInput by remember { mutableStateOf(SupabaseConfig.getSupabaseKey(context)) }
    var showKey by remember { mutableStateOf(false) }

    val isConfigured by viewModel.isSupabaseConfigured.collectAsStateWithLifecycle()
    val isSyncing by viewModel.isSyncing.collectAsStateWithLifecycle()

    var statusMessage by remember { mutableStateOf<String?>(null) }
    var isSuccessStatus by remember { mutableStateOf(true) }
    var showSqlSchema by remember { mutableStateOf(false) }

    val lastSync = SupabaseConfig.getLastSyncTime(context)

    val sqlSchemaText = """
-- SKRIP TABEL SUPABASE UNTUK WALI ASUH CARE
-- Salin dan jalankan di menu SQL Editor di dashboard Supabase Anda:

create table if not exists public.child_students (
  id bigint primary key generated by default as identity,
  name text not null,
  nis text,
  gender text,
  age integer,
  dormitory text,
  class_grade text,
  allergies text default 'Tidak ada',
  blood_type text default '-',
  emergency_contact text default 'Pengasuh Asrama',
  special_notes text default '',
  nik text default '',
  no_kk text default '',
  birth_place text default '',
  birth_date text default '',
  mother_name text default '',
  address text default '',
  room_number text default '',
  jenjang text default '',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.medical_records (
  id bigint primary key generated by default as identity,
  student_id bigint not null,
  student_name text not null,
  student_dormitory text,
  faskes text not null,
  complaint text not null,
  is_direct_treatment boolean default false,
  plan_date bigint not null,
  departure_time text default '08:30',
  status text default 'PLANNED',
  treatment_date bigint,
  diagnosis text default '',
  actions_taken text default '',
  prescription text default '',
  needs_control boolean default false,
  control_date bigint,
  is_control_completed boolean default false,
  escort_name text default '',
  notes text default '',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Buka izin akses baca & tulis untuk anon key
alter table public.child_students enable row level security;
alter table public.medical_records enable row level security;

create policy "Akses Penuh child_students" on public.child_students for all using (true) with check (true);
create policy "Akses Penuh medical_records" on public.medical_records for all using (true) with check (true);
    """.trimIndent()

    ModalBottomSheet(
        onDismissRequest = onDismiss,
        sheetState = rememberModalBottomSheetState(skipPartiallyExpanded = true),
        shape = RoundedCornerShape(topStart = 24.dp, topEnd = 24.dp),
        dragHandle = { BottomSheetDefaults.DragHandle() },
        containerColor = MaterialTheme.colorScheme.surface
    ) {
        Box(
            modifier = Modifier.fillMaxWidth(),
            contentAlignment = Alignment.Center
        ) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .widthIn(max = 640.dp)
                    .verticalScroll(rememberScrollState())
                    .padding(horizontal = 16.dp)
                    .padding(bottom = 28.dp),
                verticalArrangement = Arrangement.spacedBy(12.dp)
            ) {
                // Header
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Column {
                        Text(
                            text = "Koneksi Database Supabase",
                            fontWeight = FontWeight.Bold,
                            fontSize = 18.sp,
                            color = MaterialTheme.colorScheme.onSurface
                        )
                        Text(
                            text = "Sinkronisasi Cloud PostgreSQL antar Wali Asuh",
                            fontSize = 11.5.sp,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }

                    // Connection Status Badge
                    Card(
                        colors = CardDefaults.cardColors(
                            containerColor = if (isConfigured) Color(0xFF10B981).copy(alpha = 0.15f) else MaterialTheme.colorScheme.surfaceVariant
                        ),
                        shape = RoundedCornerShape(8.dp)
                    ) {
                        Row(
                            modifier = Modifier.padding(horizontal = 8.dp, vertical = 4.dp),
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Icon(
                                imageVector = if (isConfigured) Icons.Default.CloudDone else Icons.Default.CloudOff,
                                contentDescription = null,
                                tint = if (isConfigured) Color(0xFF10B981) else Color.Gray,
                                modifier = Modifier.size(14.dp)
                            )
                            Spacer(modifier = Modifier.width(4.dp))
                            Text(
                                text = if (isConfigured) "Terkoneksi" else "Belum Diatur",
                                fontSize = 11.sp,
                                fontWeight = FontWeight.SemiBold,
                                color = if (isConfigured) Color(0xFF065F46) else Color.Gray
                            )
                        }
                    }
                }

                HorizontalDivider()

                // Status Message Banner (if any)
                if (statusMessage != null) {
                    Card(
                        colors = CardDefaults.cardColors(
                            containerColor = if (isSuccessStatus) Color(0xFF10B981).copy(alpha = 0.12f) else MaterialTheme.colorScheme.errorContainer.copy(alpha = 0.5f)
                        ),
                        shape = RoundedCornerShape(10.dp)
                    ) {
                        Text(
                            text = statusMessage ?: "",
                            fontSize = 12.sp,
                            color = if (isSuccessStatus) Color(0xFF047857) else MaterialTheme.colorScheme.onErrorContainer,
                            modifier = Modifier.padding(10.dp)
                        )
                    }
                }

                // Project URL Input
                OutlinedTextField(
                    value = urlInput,
                    onValueChange = { urlInput = it },
                    label = { Text("Project URL Supabase") },
                    placeholder = { Text("https://xyzproject.supabase.co") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(10.dp)
                )

                // Anon Key Input
                OutlinedTextField(
                    value = keyInput,
                    onValueChange = { keyInput = it },
                    label = { Text("Anon / Public API Key") },
                    placeholder = { Text("eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9...") },
                    singleLine = true,
                    visualTransformation = if (showKey) VisualTransformation.None else PasswordVisualTransformation(),
                    trailingIcon = {
                        IconButton(onClick = { showKey = !showKey }) {
                            Icon(
                                imageVector = if (showKey) Icons.Default.VisibilityOff else Icons.Default.Visibility,
                                contentDescription = "Tampilkan Kunci"
                            )
                        }
                    },
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(10.dp)
                )

                // Save & Test Button
                Button(
                    onClick = {
                        SupabaseConfig.saveCredentials(context, urlInput, keyInput)
                        SupabaseClient.invalidateCache()
                        viewModel.testSupabaseConnection { success, msg ->
                            isSuccessStatus = success
                            statusMessage = msg
                        }
                    },
                    enabled = !isSyncing && urlInput.isNotBlank() && keyInput.isNotBlank(),
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(10.dp)
                ) {
                    if (isSyncing) {
                        CircularProgressIndicator(
                            color = Color.White,
                            modifier = Modifier.size(16.dp),
                            strokeWidth = 2.dp
                        )
                        Spacer(modifier = Modifier.width(8.dp))
                        Text("Memeriksa Koneksi...")
                    } else {
                        Icon(imageVector = Icons.Default.CloudSync, contentDescription = null, modifier = Modifier.size(18.dp))
                        Spacer(modifier = Modifier.width(6.dp))
                        Text("Simpan & Uji Koneksi Supabase")
                    }
                }

                if (lastSync > 0) {
                    Text(
                        text = "Terakhir disinkronkan: ${DateUtils.formatDateTime(lastSync)}",
                        fontSize = 11.sp,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }

                HorizontalDivider(modifier = Modifier.padding(vertical = 4.dp))

                // Action 1: Two-way sync medical records
                OutlinedButton(
                    onClick = {
                        viewModel.syncWithSupabase { success, msg ->
                            isSuccessStatus = success
                            statusMessage = msg
                        }
                    },
                    enabled = !isSyncing && isConfigured,
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(10.dp)
                ) {
                    Icon(imageVector = Icons.Default.CloudSync, contentDescription = null, modifier = Modifier.size(18.dp))
                    Spacer(modifier = Modifier.width(6.dp))
                    Text("Sinkronkan Rekam Medis Sekarang (Dua Arah)")
                }

                // Action 2: Upload 342 Students to Supabase
                OutlinedButton(
                    onClick = {
                        viewModel.uploadAllStudentsToSupabase { success, msg ->
                            isSuccessStatus = success
                            statusMessage = msg
                        }
                    },
                    enabled = !isSyncing && isConfigured,
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(10.dp)
                ) {
                    Icon(imageVector = Icons.Default.CloudUpload, contentDescription = null, modifier = Modifier.size(18.dp))
                    Spacer(modifier = Modifier.width(6.dp))
                    Text("Unggah 342 Data Siswa SRT 1 ke Supabase")
                }

                Spacer(modifier = Modifier.height(4.dp))

                // SQL Script Section
                Card(
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.4f)),
                    shape = RoundedCornerShape(10.dp)
                ) {
                    Column(modifier = Modifier.padding(12.dp)) {
                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.SpaceBetween,
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Text(
                                text = "Panduan Skrip Tabel Supabase (SQL)",
                                fontWeight = FontWeight.Bold,
                                fontSize = 12.sp,
                                color = MaterialTheme.colorScheme.onSurface
                            )
                            IconButton(
                                onClick = {
                                    val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
                                    val clip = ClipData.newPlainText("SQL Schema", sqlSchemaText)
                                    clipboard.setPrimaryClip(clip)
                                    Toast.makeText(context, "Skrip SQL berhasil disalin!", Toast.LENGTH_SHORT).show()
                                }
                            ) {
                                Icon(
                                    imageVector = Icons.Default.ContentCopy,
                                    contentDescription = "Salin Skrip SQL",
                                    tint = WaliPrimary,
                                    modifier = Modifier.size(18.dp)
                                )
                            }
                        }

                        Text(
                            text = "Jika Anda baru membuat project Supabase, salin skrip SQL ini lalu paste di menu SQL Editor Supabase untuk membuat tabel secara otomatis.",
                            fontSize = 11.sp,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                }

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.End
                ) {
                    Button(
                        onClick = onDismiss,
                        shape = RoundedCornerShape(10.dp)
                    ) {
                        Text("Selesai")
                    }
                }
            }
        }
    }
}
